public class Main {

    public static void main(String[] args) {
        // A. インスタンスを生成することはできない。 → 〇：できない。
        // A a = new A();

        B b = new B();
        b.A2();
        b.display_num_in_B();

        D d = new D();
        d.C1();
    }
}

