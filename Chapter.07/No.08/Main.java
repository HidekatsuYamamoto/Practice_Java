//
// B. 抽象クラスのメソッドはオーバーライドできない。
// 誤り：むしろ抽象クラスの抽象メソッドをオーバーライドして実装します。
//
// C. サブクラスから抽象クラスの公開フィールドに自由にアクセス
// できる。
// 正しい：できる。
//
// D. 抽象クラスを継承した抽象クラスを定義できる。
// 正しい：できる。
//
// E. 抽象クラスは、すべてのサブクラスが実装しなければならない。
// 誤り：抽象クラスを継承した抽象クラスがあります。
