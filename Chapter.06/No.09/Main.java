// 9. 次のプログラムの空欄に記述できるコードとして、正しいものを選びなさい（２つ選択）。
public class Main {
    public static void main(String[] args) {
        int a = 1;
        int b = 2;
        // [ 空欄 ]
        int c = b;
    }
}

// A. System.out.println(a);
// B. System.out.println(b + 2);
// C. System.out.println(c);
// D. System.out.println(d);

// 正解は、A と B です。C と D は、変数 c と d が宣言されていないため、エラーになります。